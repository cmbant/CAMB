"""Generate exact divided series coefficients for the second Airy map correction.
F(t)=P(t)R(t)^3-5525+750E(t)-125E(t)^2.
For each j, F_j(a,b) is homogeneous symmetric; represent via p=a+b,q=ab.
"""

import sympy as S

N = 16
h = S.Symbol("h")
R = [S.Poly(S.Rational(3, 2 * j + 3) * sum(h**i for i in range(j + 1)), h) for j in range(N + 1)]
E = [S.Poly(0, h), S.Poly(0, h)] + [R[j] - R[1] * R[j - 1] for j in range(2, N + 1)]


def conv(a, b, n):
    return [
        sum((a[i] * b[j - i] for i in range(max(0, j + 1 - len(b)), min(j + 1, len(a)))), S.Poly(0, h))
        for j in range(n + 1)
    ]


P = [
    5525,
    -9945 * (1 + h),
    4779 + 16983 * h + 4779 * h * h,
    -375 * (1 + h**3) - 7395 * h * (1 + h),
    405 * h * (1 + h * h) + 2610 * h * h,
]
P = [S.Poly(p, h) for p in P]
F = conv(P, conv(R, conv(R, R, N), N), N)
E2 = conv(E, E, N)
F = [F[j] + 750 * E[j] - 125 * E2[j] - (5525 if j == 0 else 0) for j in range(N + 1)]
assert all(f.is_zero for f in F[:5])
co = []
for j in range(5, N + 1):
    f = F[j]
    c = []
    for m in range(j // 2 + 1):
        v = f.nth(m)
        c.append(v)
        f -= S.Poly(v * h**m * (1 + h) ** (j - 2 * m), h)
    assert f.is_zero
    co.append(c + [0] * (9 - len(c)))
import sys

with open(sys.argv[1] if len(sys.argv) > 1 else "airy_local.inc", "w") as out:
    out.write("! Generated by tests/generate_refined_airy.py using exact rational polynomial arithmetic.\n")
    out.write("real(dl),parameter::F_local(0:8,5:16)=reshape([ &\n")
    vals = [f"{float(v):.17e}_dl" for c in co for v in c]
    out.writelines(
        ", ".join(vals[i : i + 3]) + (", &\n" if i + 3 < len(vals) else " ], [9,12])\n") for i in range(0, len(vals), 3)
    )
print("verified five removable zero coefficients; exact symmetric basis for j=5..16")
